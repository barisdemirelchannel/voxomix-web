// Language is determined by the first URL path segment so each URL is
// single-language and independently indexable: /en/... => English,
// /es/... => Spanish, /fr/... => French, /de/... => German, else Turkish.
const SUPPORTED_LANGS = ['en', 'es', 'fr', 'de', 'it'];
function voxomixLang() {
  const seg = location.pathname.replace(/^\/+/, '').toLowerCase().split('/')[0];
  return SUPPORTED_LANGS.includes(seg) ? seg : 'tr';
}

(function () {
  const lang = voxomixLang();
  const t = translations[lang];

  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  // Billing toggle labels (now from the dictionary, not hard-coded per language)
  const btnMonthly = document.getElementById('btn-monthly');
  const btnYearly  = document.getElementById('btn-yearly');
  if (btnMonthly) btnMonthly.textContent = t['billing.monthly'];
  if (btnYearly)  btnYearly.textContent  = t['billing.yearly'];

  const billingNote = document.getElementById('billing-note');
  if (billingNote) billingNote.textContent = t['billing.note'];

  // ── 5-language switcher. Upgrades the single .nav-lang toggle into a dropdown
  // and the mobile menu's language link into an inline row, so no per-page
  // markup change is needed — every page that loads i18n.js gets all 5 languages.
  // Each link targets that language's homepage (always a valid URL); per-page
  // SEO cross-linking is handled separately by <link rel="alternate" hreflang>.
  // Alfabetik sıra (etiket = kod sırasıyla aynı): Deutsch, English, Español, Français, Türkçe
  const LANGS = [
    { code: 'de', label: 'Deutsch',  url: '/de/' },
    { code: 'en', label: 'English',  url: '/en/' },
    { code: 'es', label: 'Español',  url: '/es/' },
    { code: 'fr', label: 'Français', url: '/fr/' },
    { code: 'it', label: 'Italiano', url: '/it/' },
    { code: 'tr', label: 'Türkçe',   url: '/'    },
  ];
  const cur = LANGS.find(l => l.code === lang) || LANGS[0];

  // Desktop: replace .nav-lang with a dropdown
  document.querySelectorAll('.nav-lang').forEach(function (el) {
    const dd = document.createElement('div');
    dd.className = 'nav-lang-dd';
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'nav-lang';
    btn.setAttribute('aria-haspopup', 'true');
    btn.setAttribute('aria-expanded', 'false');
    btn.innerHTML = '🌐 ' + cur.code.toUpperCase() + ' ▾';
    const menu = document.createElement('div');
    menu.className = 'nav-lang-menu';
    LANGS.forEach(function (l) {
      const a = document.createElement('a');
      a.href = l.url; a.textContent = l.label; a.hreflang = l.code;
      if (l.code === lang) a.className = 'active';
      a.addEventListener('click', function () { try { localStorage.setItem('voxomix_site_lang', l.code); } catch (e) {} });
      menu.appendChild(a);
    });
    dd.appendChild(btn); dd.appendChild(menu);
    btn.addEventListener('click', function (e) {
      e.preventDefault();
      const open = dd.classList.toggle('open');
      btn.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    el.replaceWith(dd);
  });
  document.addEventListener('click', function (e) {
    if (!e.target.closest('.nav-lang-dd')) {
      document.querySelectorAll('.nav-lang-dd.open').forEach(function (d) { d.classList.remove('open'); });
    }
  });

  // Hamburger'ı olmayan sayfalar (blog index + yazılar) mevcut nav'dan bir
  // hamburger + mobil menü ÜRETİR; böylece mobilde ana sayfayla aynı temiz
  // logo+menü görünümü olur ve dil seçici kaybolmaz. Ana sayfada zaten hamburger
  // + #mobile-menu var → erken çık. Aşağıdaki dil-satırı kodundan ÖNCE çalışmalı.
  (function () {
    const nav = document.querySelector('nav');
    if (!nav || nav.querySelector('.hamburger') || document.getElementById('mobile-menu')) return;
    const base = lang === 'tr' ? '' : '/' + lang;
    const cta = nav.querySelector('.nav-cta');
    if (cta) cta.classList.add('desktop-cta');           // uzun CTA'yı mobilde gizle
    const burger = document.createElement('button');
    burger.className = 'hamburger'; burger.id = 'hamburger';
    burger.setAttribute('aria-label', 'Menu');
    burger.innerHTML = '<span></span><span></span><span></span>';
    nav.appendChild(burger);
    const menu = document.createElement('div');
    menu.className = 'mobile-menu'; menu.id = 'mobile-menu';
    [[t['nav.features'], base + '/#features'],
     [t['nav.download'], base + '/#download'],
     [t['nav.plans'],    base + '/#plans'],
     ['Blog',            base + '/blog/'],
     [t['nav.about'],    base + '/hakkimizda']].forEach(function (l) {
      const a = document.createElement('a'); a.href = l[1]; a.textContent = l[0]; menu.appendChild(a);
    });
    const seed = document.createElement('a');            // dil-satırı kodu bunu değiştirir
    seed.href = '/'; seed.hreflang = 'tr'; seed.textContent = 'Türkçe';
    menu.appendChild(seed);
    const mcta = document.createElement('a');
    mcta.href = base + '/#download'; mcta.className = 'nav-cta';
    mcta.style.textAlign = 'center'; mcta.style.marginTop = '8px';
    mcta.textContent = t['nav.ctaShort'] || t['nav.cta'] || 'Free';
    menu.appendChild(mcta);
    nav.insertAdjacentElement('afterend', menu);
    burger.addEventListener('click', function () {
      burger.classList.toggle('open'); menu.classList.toggle('open');
    });
    menu.querySelectorAll('a').forEach(function (a) {
      a.addEventListener('click', function () { burger.classList.remove('open'); menu.classList.remove('open'); });
    });
  })();

  // Mobile: replace the menu's single language link with an inline 5-language row
  const mLangLink = document.querySelector('.mobile-menu a[hreflang]');
  if (mLangLink) {
    const row = document.createElement('div');
    row.className = 'mobile-lang-row';
    LANGS.forEach(function (l) {
      const a = document.createElement('a');
      a.href = l.url; a.textContent = l.code.toUpperCase(); a.hreflang = l.code;
      if (l.code === lang) a.className = 'active';
      a.addEventListener('click', function () { try { localStorage.setItem('voxomix_site_lang', l.code); } catch (e) {} });
      row.appendChild(a);
    });
    mLangLink.replaceWith(row);
  }
})();

// Billing toggle function (global). Prices are USD everywhere (Polar charges USD
// abroad; the Turkish iyzico flow shows its own TRY amounts at checkout).
const _prices = {
  basic:    { monthly: '$2<span>.99</span>',  yearly: '$2<span>.39</span>' },
  student:  { monthly: '$8<span>.99</span>',  yearly: '$7<span>.19</span>' },
  producer: { monthly: '$13<span>.99</span>', yearly: '$11<span>.19</span>' },
};
const _periods = {
  tr: { monthly: '/ ay',    yearly: '/ ay' },
  en: { monthly: '/ month', yearly: '/ month' },
  es: { monthly: '/ mes',   yearly: '/ mes' },
  fr: { monthly: '/ mois',  yearly: '/ mois' },
  de: { monthly: '/ Monat', yearly: '/ Monat' },
  it: { monthly: '/ mese',  yearly: '/ mese' },
};
const _currentLang = voxomixLang();

function setBilling(mode) {
  const priceBasic    = document.getElementById('price-basic');
  const priceStudent  = document.getElementById('price-student');
  const priceProducer = document.getElementById('price-producer');
  const periodBasic    = document.getElementById('period-basic');
  const periodStudent  = document.getElementById('period-student');
  const periodProducer = document.getElementById('period-producer');
  const btnMonthly  = document.getElementById('btn-monthly');
  const btnYearly   = document.getElementById('btn-yearly');
  const note        = document.getElementById('billing-note');

  if (priceBasic)    priceBasic.innerHTML    = _prices.basic[mode];
  if (priceStudent)  priceStudent.innerHTML  = _prices.student[mode];
  if (priceProducer) priceProducer.innerHTML = _prices.producer[mode];
  const per = _periods[_currentLang][mode];
  if (periodBasic)    periodBasic.textContent    = per;
  if (periodStudent)  periodStudent.textContent  = per;
  if (periodProducer) periodProducer.textContent = per;
  if (note)        note.style.display = mode === 'yearly' ? 'block' : 'none';
  if (btnMonthly)  btnMonthly.classList.toggle('active', mode === 'monthly');
  if (btnYearly)   btnYearly.classList.toggle('active', mode === 'yearly');
}
